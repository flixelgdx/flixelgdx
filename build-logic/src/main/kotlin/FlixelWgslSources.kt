import org.gradle.api.DefaultTask
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.provider.MapProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.CacheableTask
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.InputFiles
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.PathSensitive
import org.gradle.api.tasks.PathSensitivity
import org.gradle.api.tasks.TaskAction
import java.io.File

/**
 * Turns WGSL files into string constants of a generated Java class.
 *
 * The framework's built-in shaders are compiled into the program instead of being read from the classpath at run
 * time, because not every platform can read classpath resources (a browser has no classpath at all). The `.wgsl`
 * files stay the single source of truth: this task rewrites the Java class whenever one of them changes.
 *
 * Register it in a module and add its output to the main Java sources:
 *
 * ```kotlin
 * val wgslSources = tasks.register<FlixelWgslSources>("generateWgslSources") {
 *   packageName = "org.example"
 *   className = "ExampleShaders"
 *   shaders.put("SPRITE", layout.projectDirectory.file("src/main/wgsl/sprite.wgsl").asFile.path)
 *   outputDir = layout.buildDirectory.dir("generated/sources/wgsl/main/java")
 * }
 * sourceSets.main { java.srcDir(wgslSources) }
 * ```
 */
@CacheableTask
abstract class FlixelWgslSources : DefaultTask() {

  /** The package of the generated class. */
  @get:Input
  abstract val packageName: Property<String>

  /** The simple name of the generated class. */
  @get:Input
  abstract val className: Property<String>

  /** Maps each constant name to the path of the WGSL file it holds, in the order the constants are written. */
  @get:Input
  abstract val shaders: MapProperty<String, String>

  /** The source root the class is written under. */
  @get:OutputDirectory
  abstract val outputDir: DirectoryProperty

  /** The WGSL files, tracked so the class is regenerated when one of them changes. */
  @get:InputFiles
  @get:PathSensitive(PathSensitivity.RELATIVE)
  val shaderFiles: List<File>
    get() = shaders.get().values.map(::File)

  init {
    group = "build"
    description = "Turns the built-in WGSL shaders into Java string constants."
  }

  @TaskAction
  fun generate() {
    val pkg = packageName.get()
    val name = className.get()
    val dir = outputDir.get().asFile.resolve(pkg.replace('.', '/'))
    dir.deleteRecursively()
    dir.mkdirs()
    val out = StringBuilder()
    out.append("/*\n * Generated by the FlixelWgslSources task of the FlixelGDX build. Do not edit: change the .wgsl\n")
    out.append(" * files instead.\n */\n")
    out.append("package ").append(pkg).append(";\n\n")
    out.append("/** The source text of built-in WGSL shaders, generated from their {@code .wgsl} files. */\n")
    out.append("public final class ").append(name).append(" {\n")
    for ((constant, path) in shaders.get()) {
      val file = File(path)
      if (!file.isFile) {
        throw org.gradle.api.GradleException("The WGSL file for $constant does not exist: $path")
      }
      out.append("\n  /** The contents of {@code ").append(file.name).append("}. */\n")
      out.append("  public static final String ").append(constant).append(" =")
      val lines = file.readText().replace("\r\n", "\n").split('\n')
      // A file ending with a line break splits into a trailing empty string, which is not a line of its own.
      val count = if (lines.last().isEmpty()) lines.size - 1 else lines.size
      if (count == 0) {
        out.append(" \"\";\n")
        continue
      }
      for (i in 0 until count) {
        val last = i == count - 1
        val text = escape(lines[i]) + if (last && lines.size == count) "" else "\\n"
        out.append("\n      \"").append(text).append('"').append(if (last) ";" else " +")
      }
      out.append('\n')
    }
    out.append("\n  private ").append(name).append("() {}\n}\n")
    File(dir, "$name.java").writeText(out.toString())
  }

  private fun escape(line: String): String {
    val sb = StringBuilder(line.length + 8)
    for (c in line) {
      when {
        c == '\\' -> sb.append("\\\\")
        c == '"' -> sb.append("\\\"")
        c == '\t' -> sb.append("\\t")
        c.code < 0x20 || c.code > 0x7E -> sb.append(String.format("\\u%04x", c.code))
        else -> sb.append(c)
      }
    }
    return sb.toString()
  }
}
