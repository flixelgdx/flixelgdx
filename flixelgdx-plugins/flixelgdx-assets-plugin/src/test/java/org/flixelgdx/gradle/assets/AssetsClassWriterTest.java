package org.flixelgdx.gradle.assets;

import org.gradle.api.GradleException;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;

import javax.tools.JavaCompiler;
import javax.tools.ToolProvider;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

class AssetsClassWriterTest {

  @TempDir
  Path dir;

  @Test
  void writesNestedClassesAndConstants() {
    String source = AssetsClassWriter.write("com.mygame", "Assets",
        List.of("shared/sprites/player.png", "music/theme.ogg", "logo.png"));

    assertTrue(source.startsWith("// Generated by"), source);
    assertTrue(source.contains("package com.mygame;\n"), source);
    assertTrue(source.contains("public final class Assets {\n"), source);
    assertTrue(source.contains("  public static final String LOGO_PNG = \"logo.png\";\n"), source);
    assertTrue(source.contains("  public static final class Music {\n"), source);
    assertTrue(source.contains("    public static final String THEME_OGG = \"music/theme.ogg\";\n"), source);
    assertTrue(source.contains("    public static final class Sprites {\n"), source);
    assertTrue(source.contains("      public static final String PLAYER_PNG = \"shared/sprites/player.png\";\n"),
        source);
    assertTrue(source.contains("private Sprites() {}"), source);
  }

  @Test
  void outputDoesNotDependOnInputOrder() {
    List<String> paths = List.of("b/z.png", "a.png", "b/a.png", "c/d/e.png");
    String first = AssetsClassWriter.write("", "Assets", paths);
    String second = AssetsClassWriter.write("", "Assets", paths.reversed());
    assertEquals(first, second);
  }

  @Test
  void constantsComeBeforeNestedClasses() {
    String source = AssetsClassWriter.write("", "Assets", List.of("a/b.png", "z.png"));
    assertTrue(source.indexOf("Z_PNG") < source.indexOf("class A "), source);
  }

  @Test
  void emptyFolderListGivesAnEmptyClass() throws IOException {
    String source = AssetsClassWriter.write("com.mygame", "Assets", List.of());
    assertTrue(source.contains("private Assets() {}"), source);
    compile("com/mygame/Assets.java", source);
  }

  @Test
  void defaultPackageHasNoPackageLine() {
    assertFalse(AssetsClassWriter.write("", "Assets", List.of("a.png")).contains("package "));
  }

  @Test
  void siblingFilesThatClashFailWithBothPaths() {
    GradleException e = assertThrows(GradleException.class,
        () -> AssetsClassWriter.write("", "Assets", List.of("music/my-song.ogg", "music/my_song.ogg")));
    assertTrue(e.getMessage().contains("music/my-song.ogg"), e.getMessage());
    assertTrue(e.getMessage().contains("music/my_song.ogg"), e.getMessage());
    assertTrue(e.getMessage().contains("MY_SONG_OGG"), e.getMessage());
  }

  @Test
  void siblingFoldersThatClashFail() {
    GradleException e = assertThrows(GradleException.class,
        () -> AssetsClassWriter.write("", "Assets", List.of("ui-icons/a.png", "ui_icons/b.png")));
    assertTrue(e.getMessage().contains("UiIcons"), e.getMessage());
  }

  @Test
  void sameNameInDifferentFoldersIsFine() {
    String source = AssetsClassWriter.write("", "Assets", List.of("a/x.png", "b/x.png"));
    assertTrue(source.contains("\"a/x.png\""), source);
    assertTrue(source.contains("\"b/x.png\""), source);
  }

  @Test
  void fileAndFolderWithTheSameNameAreFine() {
    assertTrue(AssetsClassWriter.write("", "Assets", List.of("a", "a/b.png")).contains("String A = \"a\""));
  }

  @Test
  void folderNamedLikeItsEnclosingClassFails() {
    GradleException e = assertThrows(GradleException.class,
        () -> AssetsClassWriter.write("", "Assets", List.of("sprites/sprites/player.png")));
    assertTrue(e.getMessage().contains("sprites/sprites"), e.getMessage());
    assertThrows(GradleException.class, () -> AssetsClassWriter.write("", "Assets", List.of("assets/a.png")));
  }

  @Test
  void nameWithoutLettersOrDigitsFails() {
    GradleException e =
        assertThrows(GradleException.class, () -> AssetsClassWriter.write("", "Assets", List.of("music/---")));
    assertTrue(e.getMessage().contains("music/---"), e.getMessage());
  }

  @Test
  void invalidPackageOrClassNameFails() {
    assertThrows(GradleException.class, () -> AssetsClassWriter.write("my-game", "Assets", List.of()));
    assertThrows(GradleException.class, () -> AssetsClassWriter.write("com..game", "Assets", List.of()));
    assertThrows(GradleException.class, () -> AssetsClassWriter.write("com.class", "Assets", List.of()));
    assertThrows(GradleException.class, () -> AssetsClassWriter.write("com.game", "My Assets", List.of()));
  }

  @Test
  void stringsAreEscapedAndAscii() {
    assertEquals("q\\\"uote", AssetsClassWriter.escapeString("q\"uote"));
    assertEquals("back\\\\slash", AssetsClassWriter.escapeString("back\\slash"));
    assertEquals("caf\\u00e9", AssetsClassWriter.escapeString("café"));
  }

  @Test
  void docTextCannotEndTheComment() {
    String doc = AssetsClassWriter.escapeDoc("star*/x {@code} <b> \\u0041 &");
    assertFalse(doc.contains("*/"), doc);
    assertFalse(doc.contains("{@"), doc);
    assertFalse(doc.contains("<b>"), doc);
    assertFalse(doc.contains("\\"), doc);
  }

  @Test
  void strangeFileNamesStillCompileWithStrictDoclint() throws IOException {
    String source = AssetsClassWriter.write("com.mygame", "Assets", List.of(
        "star*/x.png",
        "q\"uote.png",
        "back\\slash.png",
        "uni\\u0041code.png",
        "café-theme.ogg",
        "{@code tag}.png",
        "<b>bold</b>.png",
        "amp&ersand.txt",
        "8bit.ogg"));
    assertTrue(source.chars().allMatch(c -> c < 0x80), "The generated source should be ASCII only.");
    compile("com/mygame/Assets.java", source);
  }

  private void compile(String relative, String source) throws IOException {
    Path file = dir.resolve("src").resolve(relative);
    Files.createDirectories(file.getParent());
    Files.writeString(file, source, StandardCharsets.UTF_8);
    JavaCompiler javac = ToolProvider.getSystemJavaCompiler();
    ByteArrayOutputStream err = new ByteArrayOutputStream();
    int code = javac.run(null, null, err, "-Xdoclint:all/protected", "-Werror", "-d", dir.resolve("classes").toString(),
        file.toString());
    assertEquals(0, code, err.toString(StandardCharsets.UTF_8) + "\n" + source);
  }
}
