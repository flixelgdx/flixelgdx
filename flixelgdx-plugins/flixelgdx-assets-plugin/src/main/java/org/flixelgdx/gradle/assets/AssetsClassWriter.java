package org.flixelgdx.gradle.assets;

import org.gradle.api.GradleException;

import java.util.ArrayList;
import java.util.Collection;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;

/**
 * Writes the Java source of the generated assets class from a list of asset paths.
 *
 * <p>Think of it as turning a filing cabinet into a table of contents: every drawer (folder) becomes a chapter (a
 * nested class), and every sheet (file) becomes a line that tells you exactly where to find it (a constant holding its
 * path). For example, the paths {@code music/theme.ogg} and {@code shared/sprites/player.png} become:
 *
 * <pre>{@code
 * public final class Assets {
 *   public static final class Music {
 *     public static final String THEME_OGG = "music/theme.ogg";
 *   }
 *   public static final class Shared {
 *     public static final class Sprites {
 *       public static final String PLAYER_PNG = "shared/sprites/player.png";
 *     }
 *   }
 * }
 * }</pre>
 *
 * <p>The output only depends on the paths and the names, not on the order the paths come in, so the same folder
 * always produces byte-for-byte the same file. Two names that turn into the same identifier (such as
 * {@code my-song.ogg} and {@code my_song.ogg}) fail the build with a message naming both files, since quietly picking
 * one would hand the game the wrong asset.
 *
 * @see AssetNames
 */
public final class AssetsClassWriter {

  private static final String INDENT = "  ";

  private AssetsClassWriter() {}

  /**
   * Writes the source of the assets class.
   *
   * @param packageName The package of the class, or an empty string for the default package.
   * @param className The simple name of the class, such as {@code Assets}.
   * @param paths Every asset path, relative to the assets folder and separated with forward slashes.
   * @return The complete source of the class, ending with a line break.
   * @throws GradleException if the package or class name is not valid Java, or two assets clash.
   */
  public static String write(String packageName, String className, Collection<String> paths) {
    checkNames(packageName, className);
    Folder root = new Folder(className, "");
    for (String path : paths) {
      add(root, path);
    }

    StringBuilder out = new StringBuilder();
    out.append("// Generated by the org.flixelgdx.assets Gradle plugin from the assets folder. Do not edit.\n");
    if (!packageName.isEmpty()) {
      out.append("package ").append(packageName).append(";\n");
    }
    out.append('\n');
    out.append("/**\n");
    out.append(" * Every file in the game's assets folder, as path constants grouped by folder.\n");
    out.append(" *\n");
    out.append(
        " * <p>This class is generated before the code compiles, so it always matches the assets folder. A file that\n");
    out.append(
        " * is renamed or removed makes the code that uses it fail to compile instead of failing at run time.\n");
    out.append(" */\n");
    writeFolder(out, root, new ArrayList<>(), 0);
    return out.toString();
  }

  private static void checkNames(String packageName, String className) {
    if (!packageName.isEmpty()) {
      for (String segment : packageName.split("\\.", -1)) {
        if (!AssetNames.isIdentifier(segment)) {
          throw new GradleException("'" + packageName + "' is not a valid Java package for the assets class. Set "
              + "assetsClass.packageName in the build script, for example packageName = 'com.mygame'.");
        }
      }
    }
    if (!AssetNames.isIdentifier(className)) {
      throw new GradleException("'" + className + "' is not a valid Java class name for the assets class. Set "
          + "assetsClass.className in the build script.");
    }
  }

  private static void add(Folder root, String path) {
    String[] parts = path.split("/");
    Folder folder = root;
    StringBuilder folderPath = new StringBuilder();
    for (int i = 0; i < parts.length - 1; i++) {
      String part = parts[i];
      folderPath.append(part).append('/');
      Folder child = folder.folders.get(part);
      if (child == null) {
        String childPath = folderPath.substring(0, folderPath.length() - 1);
        child = new Folder(identifier(AssetNames.toClassName(part), part, childPath), childPath);
        folder.folders.put(part, child);
      }
      folder = child;
    }
    String fileName = parts[parts.length - 1];
    folder.files.put(fileName, new Asset(identifier(AssetNames.toConstantName(fileName), fileName, path), path));
  }

  private static String identifier(String name, String original, CharSequence path) {
    if (name == null) {
      throw new GradleException("The asset '" + path + "' has no letters or digits in '" + original + "', so it "
          + "cannot be turned into a Java name. Rename it, or exclude it with assetsClass.excludes.");
    }
    return name;
  }

  private static void writeFolder(StringBuilder out, Folder folder, List<String> outer, int depth) {
    String pad = INDENT.repeat(depth);
    if (outer.contains(folder.name)) {
      // Java does not allow a nested class to share the name of a class it sits in, such as Sprites.Sprites.
      throw new GradleException("The folder '" + folder.path + "' would become the class " + folder.name
          + " inside a class with the same name, which Java does not allow. Rename the folder.");
    }
    if (depth == 0) {
      out.append("public final class ").append(folder.name).append(" {\n");
    } else {
      out.append(pad).append("/** Files in the <code>").append(escapeDoc(folder.path)).append("</code> folder. */\n");
      out.append(pad).append("public static final class ").append(folder.name).append(" {\n");
    }

    String inner = pad + INDENT;
    Map<String, Asset> constants = new TreeMap<>();
    for (Asset asset : folder.files.values()) {
      Asset clash = constants.put(asset.name, asset);
      if (clash != null) {
        throw clash(asset.name, clash.path, asset.path);
      }
    }
    for (Asset asset : constants.values()) {
      out.append('\n');
      out.append(inner).append("/** The file <code>").append(escapeDoc(asset.path)).append("</code>. */\n");
      out.append(inner).append("public static final String ").append(asset.name).append(" = \"")
          .append(escapeString(asset.path)).append("\";\n");
    }

    out.append('\n');
    out.append(inner).append("private ").append(folder.name).append("() {}\n");

    Map<String, Folder> classes = new TreeMap<>();
    for (Folder child : folder.folders.values()) {
      Folder clash = classes.put(child.name, child);
      if (clash != null) {
        throw clash(child.name, clash.path, child.path);
      }
    }
    outer.add(folder.name);
    for (Folder child : classes.values()) {
      out.append('\n');
      writeFolder(out, child, outer, depth + 1);
    }
    outer.remove(outer.size() - 1);
    out.append(pad).append("}\n");
  }

  private static GradleException clash(String name, String first, String second) {
    return new GradleException("The assets '" + first + "' and '" + second + "' would both be named " + name
        + " in the assets class. Rename one of them, or exclude it with assetsClass.excludes.");
  }

  /** Escapes text for a Java string literal, keeping the source file pure ASCII. */
  static String escapeString(String text) {
    StringBuilder out = new StringBuilder(text.length());
    for (int i = 0; i < text.length(); i++) {
      char c = text.charAt(i);
      switch (c) {
        case '"' -> out.append("\\\"");
        case '\\' -> out.append("\\\\");
        default -> {
          if (c < 0x20 || c > 0x7e) {
            out.append(String.format("\\u%04x", (int) c));
          } else {
            out.append(c);
          }
        }
      }
    }
    return out.toString();
  }

  /**
   * Escapes text for a Javadoc comment as HTML, so that no file name can end the comment, start a tag, or form a
   * unicode escape that javac would read before the comment.
   */
  static String escapeDoc(String text) {
    StringBuilder out = new StringBuilder(text.length());
    for (int i = 0; i < text.length(); i++) {
      char c = text.charAt(i);
      if (c >= 0x20 && c <= 0x7e && "&<>@{}*\\".indexOf(c) < 0) {
        out.append(c);
      } else {
        out.append("&#").append((int) c).append(';');
      }
    }
    return out.toString();
  }

  private record Asset(String name, String path) {
  }

  private static final class Folder {

    private final String name;
    private final String path;
    private final Map<String, Folder> folders = new TreeMap<>();
    private final Map<String, Asset> files = new TreeMap<>();

    private Folder(String name, String path) {
      this.name = name;
      this.path = path;
    }
  }
}
