package org.flixelgdx.collections;

import org.junit.jupiter.api.Test;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

class FlixelFloatArrayTest {

  @Test
  void addGetSet() {
    FlixelFloatArray array = new FlixelFloatArray();
    array.add(10.0f);
    array.add(20.0f);
    assertEquals(2, array.size);
    assertTrue(array.get(0) == 10.0f);
    array.set(0, 99.0f);
    assertTrue(array.get(0) == 99.0f);
  }

  @Test
  void orderedRemoveShifts() {
    FlixelFloatArray array = new FlixelFloatArray();
    array.add(10.0f);
    array.add(20.0f);
    array.add(99.0f);
    assertTrue(array.removeIndex(1) == 20.0f);
    assertEquals(2, array.size);
    assertTrue(array.get(1) == 99.0f);
  }

  @Test
  void unorderedRemoveSwapsLast() {
    FlixelFloatArray array = new FlixelFloatArray(false, 8);
    array.add(10.0f);
    array.add(20.0f);
    array.add(99.0f);
    assertTrue(array.removeIndex(0) == 10.0f);
    assertTrue(array.get(0) == 99.0f);
    assertEquals(2, array.size);
  }

  @Test
  void indexOfAndContains() {
    FlixelFloatArray array = new FlixelFloatArray();
    array.add(10.0f);
    array.add(20.0f);
    assertEquals(1, array.indexOf(20.0f));
    assertTrue(array.contains(10.0f));
    assertTrue(array.removeValue(20.0f));
    assertFalse(array.contains(20.0f));
  }

  @Test
  void stackAndEnds() {
    FlixelFloatArray array = new FlixelFloatArray();
    array.add(10.0f);
    array.add(20.0f);
    array.add(99.0f);
    assertTrue(array.first() == 10.0f);
    assertTrue(array.peek() == 99.0f);
    assertTrue(array.pop() == 99.0f);
    assertEquals(2, array.size);
  }

  @Test
  void growSetSizeAndToArray() {
    FlixelFloatArray array = new FlixelFloatArray(2);
    for (int i = 0; i < 50; i++) {
      array.add(10.0f);
    }
    assertEquals(50, array.size);
    float[] copy = array.toArray();
    assertEquals(50, copy.length);
    array.setSize(0);
    assertTrue(array.isEmpty());
  }

  @Test
  void emptyAccessThrows() {
    FlixelFloatArray array = new FlixelFloatArray();
    assertTrue(array.isEmpty());
    assertThrows(IndexOutOfBoundsException.class, array::pop);
    assertThrows(IndexOutOfBoundsException.class, () -> array.get(0));
  }
}
